def module_name(shard: Shard, path: str) -> str:
    inner = path[len(shard.root) + 1 : -3]
    name = inner.replace("/", ".")
    return name.removesuffix(".__init__")


def changed_function_globs(shard: Shard, path: str, ranges) -> list[str]:
    """mutmut name globs of top-level functions and methods touching the changed lines."""
    try:
        tree = ast.parse((ROOT / path).read_text())
    except (OSError, SyntaxError):
        return []
    module = module_name(shard, path)
    out = []

    def touches(node):
        start = min([node.lineno] + [d.lineno for d in node.decorator_list])
        return any(a <= node.end_lineno and b >= start for a, b in ranges)

    for node in tree.body:
        if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef) and touches(node):
            out.append(f"{module}.x_{node.name}__mutmut_*")
        elif isinstance(node, ast.ClassDef):
            for item in node.body:
                if isinstance(item, ast.FunctionDef | ast.AsyncFunctionDef) and touches(
                    item
                ):
                    out.append(f"{module}.x{SEP}{node.name}{SEP}{item.name}__mutmut_*")
    return out
