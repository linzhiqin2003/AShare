"""Python shards: mutmut 3 in a per-shard work directory.

Layout of ``.cache/mutate/py/<shard>/`` (the cwd mutmut runs in):

* ``src`` -> the shard's source root (repo ``src`` or ``packages/<pkg>/python``); mutmut copies
  it to ``mutants/src`` and mutates the files selected by ``only_mutate``;
* ``test``, ``pyproject.toml``, ``uv.lock`` -> repo files (mutmut copies them into ``mutants/``);
* ``mutants/{packages,crates,bench,docs,...}`` copied by us before mutmut starts.

The tests run from ``mutants/`` and their build guards insist that every package (ashare,
panelbt, panelops, paperbroker) is imported from below that directory, so PYTHONPATH lists the
copies ahead of the editable installs. ``mutants/src`` comes first: the mutated code wins.
"""

from __future__ import annotations

import ast
import configparser
import json
import os
import re
import shutil
import signal
import subprocess
import time
from pathlib import Path

from bench.mutate.common import (
    ERROR,
    KILLED,
    NO_TESTS,
    PYTHON,
    ROOT,
    SKIPPED,
    SURVIVED,
    TIMEOUT,
    WORK,
    Mutant,
    Shard,
    child_env,
    log,
)

MUTMUT = ROOT / ".venv/bin/mutmut"
SEP = "ǁ"  # mutmut's class-name separator in mangled names
COPY = ("packages", "crates", "bench", "docs", "Cargo.toml", "Cargo.lock", "README.md")
IGNORE = shutil.ignore_patterns(
    "__pycache__", "*.pyc", "target", "node_modules", "dist", ".pytest_cache"
)

STATUS = {
    "killed": KILLED,
    "caught by type check": KILLED,
    "segfault": KILLED,
    "timeout": TIMEOUT,
    "survived": SURVIVED,
    "no tests": NO_TESTS,
    "skipped": SKIPPED,
    "not checked": SKIPPED,
}


def workdir(shard: Shard, scope: str) -> Path:
    return WORK / "py" / (shard.name if scope == "full" else f"{shard.name}-{scope}")


def inner_globs(shard: Shard, narrow: str | None, files: list[str] | None):
    """only_mutate patterns, relative to the work directory (``src/...``)."""
    if files is not None:  # diff mode: exactly these repo files
        return ["src/" + f[len(shard.root) + 1 :] for f in files]
    if narrow and narrow != shard.root:
        inner = narrow[len(shard.root) + 1 :]
        if inner.endswith(".py"):
            return ["src/" + inner]
        globs = [g for g in shard.mutate if g.startswith(inner + "/")]
        return ["src/" + g for g in globs] or ["src/" + inner + "/*"]
    return ["src/" + g for g in shard.mutate]


def write_config(work: Path, shard: Shard, only: list[str]):
    base = configparser.ConfigParser()
    base.read(ROOT / "setup.cfg")
    section = dict(base["mutmut"])
    section["only_mutate"] = "\n" + "\n".join(only)
    section["do_not_mutate"] = "\n" + "\n".join(
        [x for x in section.get("do_not_mutate", "").split("\n") if x]
        + ["src/" + g for g in shard.exclude]
    )
    section["pytest_add_cli_args_test_selection"] = "\n" + "\n".join(shard.test_args())
    out = configparser.ConfigParser()
    out["mutmut"] = section
    with (work / "setup.cfg").open("w") as fh:
        fh.write(
            "# generated by bench/mutate/python.py from the repository setup.cfg\n"
        )
        out.write(fh)


def prepare(shard: Shard, scope: str, only: list[str], resume: bool = False) -> Path:
    work = workdir(shard, scope)
    if resume and (work / "mutants/src").exists():
        # mutmut keeps per-mutant verdicts in mutants/**.meta and only runs unchecked ones.
        write_config(work, shard, only)
        log(f"{shard.name}: resuming in {work.relative_to(ROOT)}")
        return work
    if work.exists():
        shutil.rmtree(work)
    (work / "mutants").mkdir(parents=True)
    os.symlink(ROOT / shard.root, work / "src")
    for name in ("test", "pyproject.toml", "uv.lock"):
        os.symlink(ROOT / name, work / name)
    for name in COPY:
        source = ROOT / name
        if source.is_dir():
            shutil.copytree(source, work / "mutants" / name, ignore=IGNORE)
        elif source.exists():
            shutil.copy2(source, work / "mutants" / name)
    if shard.root != "src":
        shutil.copytree(ROOT / "src", work / "mutants/ashare-src", ignore=IGNORE)
    (work / "mutants/src").mkdir()
    write_config(work, shard, only)
    return work


def pythonpath(work: Path, shard: Shard) -> str:
    mutants = work / "mutants"
    paths = [mutants / "src"]
    if shard.root != "src":
        paths.append(mutants / "ashare-src")
    paths += [
        p
        for p in sorted((mutants / "packages").glob("*/python"))
        if p.relative_to(mutants).as_posix() != shard.root
    ]
    return os.pathsep.join(str(p) for p in paths)


def run_shard(
    shard: Shard,
    scope: str = "full",
    narrow: str | None = None,
    files: list[str] | None = None,
    names: list[str] | None = None,
    jobs: int = 4,
    timeout: float = 3600,
    resume: bool = False,
):
    """Run mutmut on one shard. Returns (mutants, meta)."""
    only = inner_globs(shard, narrow, files)
    work = prepare(shard, scope, only, resume)
    env = child_env(PYTHONPATH=pythonpath(work, shard))
    logfile = work / "mutmut.log"
    cmd = [str(MUTMUT), "run", "--max-children", str(jobs), *(names or [])]
    log(f"{shard.name}: mutmut on {', '.join(only)}; tests: {' '.join(shard.tests)}")
    started = time.monotonic()
    with logfile.open("w") as out:
        proc = subprocess.Popen(
            cmd,
            cwd=work,
            env=env,
            stdout=out,
            stderr=subprocess.STDOUT,
            start_new_session=True,
        )
        try:
            code = proc.wait(timeout=timeout)
        except subprocess.TimeoutExpired:
            stop(proc)
            code = "timeout"
    seconds = time.monotonic() - started
    clock = work / "elapsed.txt"  # wall time summed over --resume runs
    if resume and clock.exists():
        seconds += float(clock.read_text())
    clock.write_text(f"{seconds:.1f}\n")
    meta = {
        "tool": "mutmut",
        "exit": code,
        "seconds": round(seconds, 1),
        "only_mutate": only,
        "tests": shard.tests,
        "log": str(logfile.relative_to(ROOT)),
    }
    text = logfile.read_text(errors="replace")
    meta["clean_run_passed"] = (
        "Running clean tests" in text and "Failed to run clean test" not in text
    )
    meta["forced_fail_caught"] = (
        "Running forced fail test" in text and "FAILED: Unable to force" not in text
    )
    if code != 0:
        log(f"{shard.name}: mutmut exited {code}; see {meta['log']}")
        tail = "\n".join(text.splitlines()[-15:])
        log(tail)
    dump = subprocess.run(
        [str(PYTHON), str(ROOT / "bench/mutate/mutmut_dump.py")],
        cwd=work,
        env=env,
        capture_output=True,
        text=True,
        timeout=900,
    )
    if dump.returncode:
        raise RuntimeError(f"mutmut_dump failed: {dump.stderr[-2000:]}")
    rows = json.loads(dump.stdout or "[]")
    if names:
        rows = [r for r in rows if r["exit_code"] is not None]
    mutants = [convert(shard, r) for r in rows]
    log(f"{shard.name}: {len(mutants)} mutants in {seconds:.0f}s")
    return mutants, meta


def stop(proc):
    """Terminate a session started with start_new_session, then kill what is left."""
    for sig, wait in ((signal.SIGTERM, 60), (signal.SIGKILL, 30)):
        try:
            os.killpg(proc.pid, sig)
        except ProcessLookupError:
            return
        try:
            proc.wait(timeout=wait)
            return
        except subprocess.TimeoutExpired:
            continue


def convert(shard: Shard, row) -> Mutant:
    inner = row["path"][len("src/") :]
    path = f"{shard.root}/{inner}"
    status = STATUS.get(row["status"])
    note = ""
    if status is None:
        code = row["exit_code"]
        if code == 2:  # pytest "Interrupted": the mutant broke collection
            status, note = KILLED, "collection error"
        else:
            status, note = ERROR, f"mutmut status {row['status']!r} (exit {code})"
    function = row["name"].split("__mutmut_")[0].rsplit(".", 1)[-1]
    function = function.removeprefix("x_").replace(SEP, ".").strip(".")
    line, change = locate(ROOT / path, function, row.get("diff", ""))
    return Mutant(
        id=row["name"],
        shard=shard.name,
        language="python",
        file=path,
        line=line,
        function=function,
        change=change,
        status=status,
        diff=row.get("diff", ""),
        seconds=row.get("seconds"),
        note=note,
    )


def changed_pair(diff: str):
    """First removed/added lines of a unified diff and the hunk-relative old line."""
    old_line = None
    removed = added = None
    position = 0
    for text in diff.splitlines():
        if text.startswith(("---", "+++")):
            continue
        m = re.match(r"@@ -(\d+)", text)
        if m:
            position = int(m.group(1))
            continue
        if text.startswith("-") and removed is None:
            removed, old_line = text[1:], position
        elif text.startswith("+") and added is None:
            added = text[1:]
            if old_line is None:
                old_line = position
        if not text.startswith("+"):
            position += 1
    return old_line, removed, added


def find_function(tree, dotted: str):
    parts = dotted.split(".")
    nodes = tree.body
    found = None
    for part in parts:
        found = next(
            (
                n
                for n in nodes
                if isinstance(n, ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef)
                and n.name == part
            ),
            None,
        )
        if found is None:
            return None
        nodes = found.body
    return found


def locate(path: Path, function: str, diff: str):
    """Best-effort original line number and a one-line description of the change."""
    old_line, removed, added = changed_pair(diff)
    change = f"{(removed or '').strip()}  ->  {(added or '').strip()}" if diff else ""
    try:
        source = path.read_text()
        node = find_function(ast.parse(source), function)
    except (OSError, SyntaxError):
        return 0, change
    if node is None:
        return 0, change
    start = min([node.lineno] + [d.lineno for d in node.decorator_list])
    if old_line is None:
        return start, change
    lines = source.splitlines()
    guess = start + old_line - 1
    if removed is not None:
        target = removed.strip()
        hits = [
            i + 1
            for i in range(start - 1, min(node.end_lineno, len(lines)))
            if lines[i].strip() == target
        ]
        if hits:
            guess = min(hits, key=lambda n: abs(n - guess))
    return guess, change


