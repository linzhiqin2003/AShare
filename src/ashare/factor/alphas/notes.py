def _index(table, prefix):
    out = {}
    for tag, ref, items in table:
        if tag not in TAGS:
            raise ValueError(f"未知标记：{tag}")
        for n in items:
            out.setdefault(f"{prefix}_{n:03d}", []).append((tag, ref))
    return {k: tuple(v) for k, v in out.items()}


ALPHA101_NOTES = _index(_ALPHA101, "alpha101")
GTJA191_NOTES = _index(_GTJA191, "gtja191")


def alpha158_notes(name):
    """Alpha158 原名（如 ``IMAX5``）的标记；按去掉数字后的族名匹配。"""
    family = name.rstrip("0123456789")
    out = []
    for tag, ref, families in _ALPHA158:
        if tag not in TAGS:
            raise ValueError(f"未知标记：{tag}")
        if family in families:
            out.append((tag, ref))
    return tuple(out)
